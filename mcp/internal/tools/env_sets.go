// Env sets over MCP (api-v1 v1.27 items 4 and 5): create a set from key
// names, and list sets as names and flags. No tool sends or returns a
// secret value or any preview: secret values are typed, generated, or
// revealed in the console. The one value a tool sends is a plain key's
// value at create (api-v1 v1.32 item 2); no tool returns it.

// envKeyPattern is the api-v1 env key rule.
var envKeyPattern = regexp.MustCompile(`^[A-Z_][A-Z0-9_]{0,63}$`)

// errEnvSetShape is fixed. It must not include the response body.
var errEnvSetShape = errors.New("env set response was not usable")

const maxEnvSetKeys = 64

// plainValueRule describes keys[].value (api-v1 v1.32 item 2).
const plainValueRule = "Plain (is_secret false) keys only. Never put a secret here: a secret is a generated key or a placeholder, and a plain template refers to it with ${KEY}."

// maxEnvValueBytes is the api-v1 env value limit.
const maxEnvValueBytes = 4096

const createEnvSetSchema = `{
  "type": "object",
  "additionalProperties": false,
  "required": ["project_id", "name", "keys", "idempotency_key"],
  "properties": {
    "project_id": {"type": "string", "format": "uuid"},
    "name": {"type": "string", "pattern": "^[a-z0-9][a-z0-9-]{0,47}$"},
    "idempotency_key": {"type": "string", "pattern": "^[A-Za-z0-9._:-]{1,128}$"},
    "keys": {
      "type": "array",
      "minItems": 1,
      "maxItems": 64,
      "items": {
        "type": "object",
        "additionalProperties": false,
        "required": ["key"],
        "properties": {
          "key": {"type": "string", "pattern": "^[A-Z_][A-Z0-9_]{0,63}$"},
          "generate": {
            "type": "object",
            "additionalProperties": false,
            "required": ["kind"],
            "properties": {
              "kind": {"type": "string", "enum": ["password", "hex", "base64url"]},
              "length": {"type": "integer", "minimum": 16, "maximum": 64, "description": "Password only; default 32."}
            }
          },
          "is_secret": {"type": "boolean", "description": "Placeholders and plain values; default true. A generated key is always secret."},
          "value": {"type": "string", "maxLength": 4096, "description": "` + plainValueRule + `"}
        }
      }
    }
  }
}`

type envSetGenerate struct {
	Kind   string `json:"kind"`
	Length *int   `json:"length,omitempty"`
}

type envSetKeyArg struct {
	Key      string          `json:"key"`
	Generate *envSetGenerate `json:"generate,omitempty"`
	IsSecret *bool           `json:"is_secret,omitempty"`
	Value    *string         `json:"value,omitempty"`
}

func registerCreateEnvSet(server *mcp.Server, api *apiclient.Client) {
	addTool(server, &mcp.Tool{
		Name:        "create_env_set",
		Description: "Create an env set from key names, with values only for plain keys. Nothing changes until confirm after the user agrees. Each key is generated by Deploybot (generate kind password, hex or base64url; always secret), a placeholder with no value that the user fills in the console (or through request_env_value), or a plain key (is_secret false) with its value. A placeholder is secret unless is_secret is false, and secret is the safer choice because a secret key cannot be made plain again. value: " + plainValueRule + " For example a DATABASE_URL template postgres://app:${DB_PASSWORD}@db/app beside a generated DB_PASSWORD costs the person no fill. If the plan warns that a key looks like a secret, tell the person before confirming. No secret value is sent or returned, and the plan and result name keys only: generated values are shown once to the user in the console, and a deploy that uses a placeholder still without a value is refused. Fails if the set name already exists. Does not contact any host.",
		Annotations: mutatingAnnotations(false),
		InputSchema: json.RawMessage(createEnvSetSchema),
	}, func(ctx context.Context, raw json.RawMessage) *mcp.CallToolResult {
		var in struct {
			ProjectID      string         `json:"project_id"`
			Name           string         `json:"name"`
			Keys           []envSetKeyArg `json:"keys"`
			IdempotencyKey string         `json:"idempotency_key"`
		}
		if err := decodeArgs(raw, &in); err != nil {
			return badRequest(err)
		}
		if err := validateCreateEnvSet(in.ProjectID, in.Name, in.IdempotencyKey, in.Keys); err != nil {
			return badRequest(err)
		}
		path := idPath("v1", "projects", in.ProjectID, "env-sets")
		body := struct {
			Name           string         `json:"name"`
			Keys           []envSetKeyArg `json:"keys"`
			IdempotencyKey string         `json:"idempotency_key"`
		}{in.Name, in.Keys, in.IdempotencyKey}
		status, payload, fail := postStatus(ctx, api, path, body)
		if fail != nil {
			return fail
		}
		return confirmationCatalog(status, payload)
	})
}

func validateCreateEnvSet(projectID, name, key string, keys []envSetKeyArg) error {
	if err := requireUUID("project_id", projectID); err != nil {
		return err
	}
	if err := requireCatalogName(name); err != nil {
		return err
	}
	if err := requireIdempotencyKey(key); err != nil {
		return err
	}
	if len(keys) == 0 || len(keys) > maxEnvSetKeys {
		return errors.New("keys must list 1 to 64 keys")
	}
	seen := map[string]bool{}
	for _, k := range keys {
		if !envKeyPattern.MatchString(k.Key) {
			return errors.New("invalid key name")
		}
		if seen[k.Key] {
			return fmt.Errorf("duplicate key %s", k.Key)
		}
		seen[k.Key] = true
		if k.Value != nil {
			// Secret is the default, so the caller must say plain.
			if k.Generate != nil || k.IsSecret == nil || *k.IsSecret {
				return errors.New("a value can be given only for a plain key")
			}
			if len(*k.Value) > maxEnvValueBytes || strings.ContainsAny(*k.Value, "\x00\r\n") {
				return errors.New("invalid env value")
			}
		}
		if k.Generate == nil {
			continue
		}
		switch k.Generate.Kind {
		case "password":
			if k.Generate.Length != nil && (*k.Generate.Length < 16 || *k.Generate.Length > 64) {
				return errors.New("generate.length must be 16 to 64")
			}
		case "hex", "base64url":
			if k.Generate.Length != nil {
				return errors.New("generate.length is only for kind password")
			}
		default:
			return errors.New(`generate.kind must be "password", "hex" or "base64url"`)
		}
		if k.IsSecret != nil && !*k.IsSecret {
			return errors.New("a generated value is secret")
		}
	}
	return nil
}

const listEnvSetsSchema = `{
  "type": "object",
  "additionalProperties": false,
  "required": ["project_id"],
  "properties": {
    "project_id": {"type": "string", "format": "uuid"},
    "name": {"type": "string", "pattern": "^[a-z0-9][a-z0-9-]{0,47}$", "description": "One set; omit for all."}
  }
}`

func registerListEnvSets(server *mcp.Server, api *apiclient.Client) {
	addTool(server, &mcp.Tool{
		Name:        "list_env_sets",
		Description: "List a project's env sets as key names and flags: is_secret, needs_value (a placeholder still without a value: call request_env_value so the person enters it; a deploy that uses it is refused), and reveal_pending (a generated value the user has not viewed yet). Each set has used_by, the catalog entries that name it in env_sets or secret_env. A set named @<entry> with an entry field is that entry's private set: secrets only it uses, named in its secret_env as @<entry>.KEY; change them through the entry (update_catalog_entry, request_env_value with entry). Never returns a value or a preview, even for plain keys. Each secret key with a value has console_url: the console button that shows a pending generated value once, or, for a value Deploybot generated (generated true), the Regenerate button that makes a new one. Nothing redeploys: running copies keep the old value until each entry in used_by is deployed again, and a value also set elsewhere (a database user, a first-start setting) must be changed there too. A secret the person entered by hand (generated false) has no Regenerate: they paste a new value with Edit in the console. Revealing and regenerating are the person's steps; there is no tool for them. " + linkRule + " Needs project owner or admin. Reads stored API data. Does not contact any host.",
		Annotations: readOnlyAnnotations(false),
		InputSchema: json.RawMessage(listEnvSetsSchema),
	}, func(ctx context.Context, raw json.RawMessage) *mcp.CallToolResult {
		var in struct {
			ProjectID string `json:"project_id"`
			Name      string `json:"name"`
		}
		if err := decodeArgs(raw, &in); err != nil {
			return badRequest(err)
		}
		if err := requireUUID("project_id", in.ProjectID); err != nil {
			return badRequest(err)
		}
		if in.Name != "" {
			if err := requireCatalogName(in.Name); err != nil {
				return badRequest(err)
			}
			payload, fail := get(ctx, api, idPath("v1", "projects", in.ProjectID, "env-sets", in.Name), nil)
			if fail != nil {
				return fail
			}
			set, err := projectEnvSet(payload)
			if err != nil {
				return toolError("error", errEnvSetShape.Error())
			}
			sets := []envSetView{set}
			withEnvLinks(api, in.ProjectID, sets)
			out, _ := json.Marshal(map[string]any{"items": sets})
			return present(out, summarizeEnvSets(sets))
		}
		// api-v1 v1.33 item 6: entry-private sets are listed too, with entry.
		q := url.Values{}
		q.Set("include", "private")
		payload, fail := get(ctx, api, idPath("v1", "projects", in.ProjectID, "env-sets"), q)
		if fail != nil {
			return fail
		}
		var body struct {
			Items []json.RawMessage `json:"items"`
		}
		if err := json.Unmarshal(payload, &body); err != nil || body.Items == nil {
			return toolError("error", errEnvSetShape.Error())
		}
		sets := make([]envSetView, 0, len(body.Items))
		for _, item := range body.Items {
			set, err := projectEnvSet(item)
			if err != nil {
				return toolError("error", errEnvSetShape.Error())
			}
			sets = append(sets, set)
		}
		withEnvLinks(api, in.ProjectID, sets)
		out, _ := json.Marshal(map[string]any{"items": sets})
		return present(out, summarizeEnvSets(sets))
	})
}

// envSetView is the only env set shape a tool returns: an allowlist, so a
// value or preview the API might send is dropped.
type envSetView struct {
	Name string          `json:"name"`
	Keys []envSetKeyView `json:"keys"`
	// Entry and UsedBy are api-v1 v1.33 items 6 and 4.
	Entry  string   `json:"entry,omitempty"`
	UsedBy []string `json:"used_by"`
}

// privateSetPattern is an entry-private set name (api-v1 v1.33 item 6).
var privateSetPattern = regexp.MustCompile(`^@[a-z0-9][a-z0-9-]{0,47}$`)

// anySetPattern is a shared or a private set name.
var anySetPattern = regexp.MustCompile(`^@?[a-z0-9][a-z0-9-]{0,47}$`)

// anySetName accepts a shared or a private set name.
func anySetName(name string) bool {
	return entryNamePattern.MatchString(name) || privateSetPattern.MatchString(name)
}

type envSetKeyView struct {
	Key           string `json:"key"`
	IsSecret      bool   `json:"is_secret"`
	NeedsValue    bool   `json:"needs_value"`
	RevealPending bool   `json:"reveal_pending"`
	// Generated (api-v1 v1.56) is true while the value is one the API
	// generated; only such a value can be regenerated.
	Generated bool `json:"generated"`
	// ConsoleURL (api-v1 v1.54) is set on a secret key with a value: the
	// console row's Reveal once button while reveal_pending, else, for a
	// generated value only (v1.56), its Regenerate button. A hand-entered
	// secret has none: the person pastes a new one with Edit. The agent
	// never reveals or regenerates.
	ConsoleURL string `json:"console_url,omitempty"`
}

// withEnvLinks sets console_url on each secret key with a value. A private
// set's key links to its entry, where the private keys are.
func withEnvLinks(api *apiclient.Client, projectID string, sets []envSetView) {
	for i := range sets {
		for j := range sets[i].Keys {
			k := &sets[i].Keys[j]
			if !k.IsSecret || k.NeedsValue {
				continue
			}
			if sets[i].Entry != "" {
				k.ConsoleURL = entryURL(api, projectID, sets[i].Entry)
				continue
			}
			if !k.RevealPending && !k.Generated {
				// v1.56: no Regenerate for a hand-entered value.
				continue
			}
			k.ConsoleURL = envKeyURL(api, projectID, sets[i].Name, k.Key, k.RevealPending)
		}
	}
}

func projectEnvSet(raw json.RawMessage) (envSetView, error) {
	var in struct {
		Name *string `json:"name"`
		Keys []struct {
			Key           *string `json:"key"`
			IsSecret      *bool   `json:"is_secret"`
			NeedsValue    bool    `json:"needs_value"`
			RevealPending bool    `json:"reveal_pending"`
			Generated     bool    `json:"generated"`
		} `json:"keys"`
		Entry  string   `json:"entry"`
		UsedBy []string `json:"used_by"`
	}
	if err := json.Unmarshal(raw, &in); err != nil || in.Name == nil || !anySetName(*in.Name) || in.Keys == nil {
		return envSetView{}, errEnvSetShape
	}
	out := envSetView{Name: *in.Name, Keys: make([]envSetKeyView, 0, len(in.Keys)), UsedBy: []string{}}
	if privateSetPattern.MatchString(*in.Name) && in.Entry == (*in.Name)[1:] {
		out.Entry = in.Entry
	}
	for _, e := range in.UsedBy {
		if entryNamePattern.MatchString(e) {
			out.UsedBy = append(out.UsedBy, e)
		}
	}
	for _, k := range in.Keys {
		if k.Key == nil || !envKeyPattern.MatchString(*k.Key) || k.IsSecret == nil {
			return envSetView{}, errEnvSetShape
		}
		out.Keys = append(out.Keys, envSetKeyView{Key: *k.Key, IsSecret: *k.IsSecret, NeedsValue: k.NeedsValue, RevealPending: k.RevealPending, Generated: k.Generated})
	}
	return out, nil
}

func summarizeEnvSets(sets []envSetView) string {
	if len(sets) == 0 {
		return "0 env sets."
	}
	needs, pending := 0, 0
	for _, s := range sets {
		for _, k := range s.Keys {
			if k.NeedsValue {
				needs++
			}
			if k.RevealPending {
				pending++
			}
		}
	}
	text := fmt.Sprintf("%d env sets.", len(sets))
	if len(sets) == 1 {
		text = fmt.Sprintf("env set %s, %s.", sets[0].Name, countKeys(len(sets[0].Keys)))
	}
	for _, set := range sets {
		switch {
		case set.Entry != "":
			text += fmt.Sprintf(" %s is private to entry %s.", set.Name, set.Entry)
		case len(set.UsedBy) > 0:
			text += fmt.Sprintf(" %s is used by %s.", set.Name, strings.Join(set.UsedBy, ", "))
		}
	}
	switch {
	case needs == 1:
		text += " 1 key still needs a value: call request_env_value for it; the person enters the value."
	case needs > 1:
		text += fmt.Sprintf(" %d keys still need a value: call request_env_value for each; the person enters the value.", needs)
	}
	switch {
	case pending == 1:
		text += " 1 generated value has not been shown yet; its console_url opens Reveal once."
	case pending > 1:
		text += fmt.Sprintf(" %d generated values have not been shown yet; each key's console_url opens Reveal once.", pending)
	}
	return text
}

// countKeys is "1 key" or "n keys".
func countKeys(n int) string {
	if n == 1 {
		return "1 key"
	}
	return fmt.Sprintf("%d keys", n)
}

// envSetCreated is the confirm result for an env set create: names and
// flags only.
func envSetCreated(payload json.RawMessage) *mcp.CallToolResult {
	set, err := projectEnvSet(payload)
	if err != nil {
		return toolError("error", errEnvSetShape.Error())
	}
	out, _ := json.Marshal(set)
	return present(out, fmt.Sprintf("created env set %s with %s. Generated values are revealed once, only by the person: list_env_sets gives each key's link to send them. Fill placeholders with request_env_value.", set.Name, countKeys(len(set.Keys))))
}

// envSetPayload reports whether a 201 confirm body is an env set (it has
// keys and no catalog kind).
func envSetPayload(payload json.RawMessage) bool {
	var probe map[string]json.RawMessage
	if err := json.Unmarshal(payload, &probe); err != nil {
		return false
	}
	_, hasKeys := probe["keys"]
	_, hasKind := probe["kind"]
	return hasKeys && !hasKind
}
